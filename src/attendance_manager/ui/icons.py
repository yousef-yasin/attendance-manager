def svg_markup(name: str, color: str, stroke: float = 2.0) -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
        f'stroke="{color}" stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">'
        f"{_PATHS[name]}</svg>"
    )


@lru_cache(maxsize=512)
def pixmap(name: str, color: str = "#4B5563", size: int = 18, stroke: float = 2.0) -> QPixmap:
    app = QGuiApplication.instance()
    ratio = app.devicePixelRatio() if isinstance(app, QGuiApplication) else 1.0
    ratio = max(ratio, 1.0)
    pm = QPixmap(QSize(int(size * ratio), int(size * ratio)))
    pm.fill(Qt.GlobalColor.transparent)
    renderer = QSvgRenderer(QByteArray(svg_markup(name, color, stroke).encode()))
    painter = QPainter(pm)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(painter, QRectF(0, 0, size * ratio, size * ratio))
    painter.end()
    pm.setDevicePixelRatio(ratio)
    return pm


def icon(
    name: str, color: str = "#4B5563", active_color: str | None = None, size: int = 18
) -> QIcon:
    result = QIcon()
    result.addPixmap(pixmap(name, color, size), QIcon.Mode.Normal, QIcon.State.Off)
    if active_color:
        result.addPixmap(pixmap(name, active_color, size), QIcon.Mode.Normal, QIcon.State.On)
        result.addPixmap(pixmap(name, active_color, size), QIcon.Mode.Active, QIcon.State.Off)
    result.addPixmap(pixmap(name, "#A0A6B0", size), QIcon.Mode.Disabled, QIcon.State.Off)
    return result


